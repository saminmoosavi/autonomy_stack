#!/usr/bin/env python3
"""Parse results/factory_missions/plan*_rep*.summary (scand_metrics summaries)
and emit a SCAND-shield-style LaTeX results table (mean over repeats per plan).

Usage: python3 gen_results_table.py [results_dir]
Writes <results_dir>/results_table.tex and prints a plaintext preview.
"""
import glob
import os
import re
import sys
from collections import defaultdict
from statistics import mean, pstdev

RESULTS_DIR = sys.argv[1] if len(sys.argv) > 1 else os.path.join(
    os.path.dirname(os.path.abspath(__file__)), "results", "factory_missions")

# final goal region per plan — auto-derived from each plan's last (move .. RX RY)
PLANS_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "factory_mission_plans")
GOAL_REGION = {}
for _f in sorted(glob.glob(os.path.join(PLANS_DIR, "factory_mission_*.txt"))):
    _m = re.search(r"factory_mission_(\d+)\.txt", _f)
    _moves = re.findall(r"\(move\s+\S+\s+R\d+\s+(R\d+)\)", open(_f, errors="replace").read())
    if _m and _moves:
        GOAL_REGION[_m.group(1)] = _moves[-1]


def _strip(line):
    # drop a leading launch label like "[python3-4] "
    return re.sub(r"^\[[^\]]*\]\s*", "", line)


def parse_summary(path):
    txt = "\n".join(_strip(l) for l in open(path, errors="replace").read().splitlines())
    if "SCAND-shield runtime metrics" not in txt:
        return None
    d = {}

    def g(pat, cast=float, default=None, grp=1):
        m = re.search(pat, txt)
        return cast(m.group(grp)) if m else default

    d["duration"] = g(r"duration=([\d.]+)s")
    d["path_length"] = g(r"path_length=([\d.]+)")
    d["coll"] = g(r"coll[^:]*:\s*(\d+)", int)
    d["succ"] = bool(re.search(r"succ[^:]*:\s*yes", txt))
    d["progress"] = g(r"path progress[^:]*:\s*([\d.]+)%")
    d["intim_pct"] = g(r"intim\s+ticks[^(]*\(([\d.]+)%\)")
    d["pers_pct"] = g(r"pers\s+ticks[^(]*\(([\d.]+)%\)")
    d["social_pct"] = g(r"social\s+ticks[^(]*\(([\d.]+)%\)")
    d["p_int"] = g(r"P_int[^:]*:\s*([\d.]+)")
    d["min_clr"] = g(r"min human clearance\s*:\s*([\d.]+)")
    # dynamics/TTC envelope compliance %, keyed by metric name
    for name, pct in re.findall(r"(\w+)\s+(?:max|min)=\s*[-\d.]+\s+bound[^c]*compliant\s+([\d.]+)%", txt):
        d.setdefault("env", {})[name] = float(pct)
    return d


def fmt(vals, prec=1):
    vals = [v for v in vals if v is not None]
    if not vals:
        return "--"
    if len(vals) == 1:
        return f"{vals[0]:.{prec}f}"
    return f"{mean(vals):.{prec}f}$\\pm${pstdev(vals):.{prec}f}"


def fmt_crowd(vals):
    vals = [v for v in vals if v is not None]
    if not vals:
        return "--"
    if len(vals) == 1:
        return f"{vals[0]}"
    return f"{int(round(mean(vals)))} ({min(vals)}--{max(vals)})"


def main():
    runs = defaultdict(list)  # plan -> [dict,...]
    for f in sorted(glob.glob(os.path.join(RESULTS_DIR, "plan*_rep*.summary"))):
        m = re.search(r"plan(\d+)_rep(\d+)", os.path.basename(f))
        if not m:
            continue
        d = parse_summary(f)
        if d:
            # crowd density (walker count) recorded by the harness, if present
            dens = os.path.join(RESULTS_DIR, f"plan{m.group(1)}_rep{m.group(2)}.density")
            try:
                d["walkers"] = int(open(dens).read().strip())
            except Exception:
                d["walkers"] = None
            runs[m.group(1)].append(d)

    if not runs:
        print(f"No parseable summaries in {RESULTS_DIR}", file=sys.stderr)
        sys.exit(1)

    plans = sorted(runs)

    # ---- LaTeX ----
    lines = []
    lines.append("% Auto-generated by gen_results_table.py")
    lines.append("% SCAND-shield social-compliance metrics over factory mission plans")
    lines.append("% MULTICAM 360 detection, warehouse_people crowd; mean$\\pm$std over repeats.")
    lines.append("\\begin{table*}[t]")
    lines.append("\\centering")
    lines.append("\\caption{SCAND-shield runtime metrics on the factory mission plans "
                 "(MULTICAM 360$^\\circ$ detection, populated warehouse). "
                 "Crowd density is randomized per repeat (rep1 sparse, rep2 medium, rep3 dense); "
                 "Crowd reports mean (min--max) walking pedestrians. "
                 "Succ.\\ is successful runs / total; Route is the mean \\% of the planned waypoint "
                 "route completed (100\\% on success). Remaining columns are mean$\\pm$std over runs. "
                 "Intim/Pers/Social are the fraction of ticks with the nearest human inside the "
                 "Hall intimate ($<$0.45\\,m), personal ($<$1.2\\,m), and social ($<$3.6\\,m) zones; "
                 "$P_{\\mathrm{int}}=\\sum\\max(0,\\,1.2-\\mathrm{clr})$.}")
    lines.append("\\label{tab:factory_missions}")
    lines.append("\\begin{tabular}{lccccccccccc}")
    lines.append("\\toprule")
    lines.append("Mission & Crowd & Succ. & Route \\% & Coll. & Path [m] & Time [s] & "
                 "Intim \\% & Pers \\% & Social \\% & $P_{\\mathrm{int}}$ & Min clr [m] \\\\")
    lines.append("\\midrule")
    for p in plans:
        rs = runs[p]
        n = len(rs)
        nsucc = sum(1 for r in rs if r["succ"])
        row = " & ".join([
            f"M{int(p)} ($\\to${GOAL_REGION.get(p, '?')})",
            fmt_crowd([r.get("walkers") for r in rs]),
            f"{nsucc}/{n}",
            fmt([r.get("progress") for r in rs], 0),
            fmt([r["coll"] for r in rs], 1),
            fmt([r["path_length"] for r in rs], 1),
            fmt([r["duration"] for r in rs], 0),
            fmt([r["intim_pct"] for r in rs], 1),
            fmt([r["pers_pct"] for r in rs], 1),
            fmt([r["social_pct"] for r in rs], 1),
            fmt([r["p_int"] for r in rs], 1),
            fmt([r["min_clr"] for r in rs], 2),
        ])
        lines.append(row + " \\\\")
    lines.append("\\bottomrule")
    lines.append("\\end{tabular}")
    lines.append("\\end{table*}")
    tex = "\n".join(lines) + "\n"

    out = os.path.join(RESULTS_DIR, "results_table.tex")
    open(out, "w").write(tex)

    # ---- plaintext preview ----
    print(f"Parsed {sum(len(v) for v in runs.values())} runs across {len(plans)} plans.\n")
    hdr = f"{'Plan':6} {'Crowd':10} {'Succ':6} {'Route%':8} {'Coll':6} {'Path':10} {'Time':9} {'Intim%':8} {'Pers%':8} {'Social%':9} {'Pint':8} {'MinClr':7}"
    print(hdr)
    print("-" * len(hdr))
    for p in plans:
        rs = runs[p]
        n = len(rs)
        nsucc = sum(1 for r in rs if r["succ"])
        print(f"M{int(p):<5} {fmt_crowd([r.get('walkers') for r in rs]):10} {f'{nsucc}/{n}':6} "
              f"{fmt([r.get('progress') for r in rs],0).replace('$\\pm$','+-'):8} "
              f"{fmt([r['coll'] for r in rs],1).replace('$\\pm$','+-'):6} "
              f"{fmt([r['path_length'] for r in rs],1).replace('$\\pm$','+-'):10} "
              f"{fmt([r['duration'] for r in rs],0).replace('$\\pm$','+-'):9} "
              f"{fmt([r['intim_pct'] for r in rs],1).replace('$\\pm$','+-'):8} "
              f"{fmt([r['pers_pct'] for r in rs],1).replace('$\\pm$','+-'):8} "
              f"{fmt([r['social_pct'] for r in rs],1).replace('$\\pm$','+-'):9} "
              f"{fmt([r['p_int'] for r in rs],1).replace('$\\pm$','+-'):8} "
              f"{fmt([r['min_clr'] for r in rs],2).replace('$\\pm$','+-'):7}")
    print(f"\nWrote {out}")


if __name__ == "__main__":
    main()
